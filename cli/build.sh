#!/usr/bin/env bash
set -euo pipefail
source_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
output_dir=${1:-"$source_dir/dist"}
mkdir -p -- "$output_dir"
for entry in install_release:release install_prerelease:prerelease uninstall:uninstall decky-updater:choose; do
    name=${entry%:*}; operation=${entry#*:}
    {
        printf '#!/usr/bin/env bash\n# Generated by cli/build.sh; edit cli/src instead.\n'
        # Bash parses this entire compound command before executing anything, so a
        # truncated curl stream cannot execute a partial installation.
        printf '{\nDEFAULT_OPERATION=%q\nENTRY_NAME=%q\n' "$operation" "$name.sh"
        for module in common network system main; do cat -- "$source_dir/src/$module.sh"; printf '\n'; done
        printf 'main "$@"\n}\n'
    } > "$output_dir/$name.sh"
    chmod 0755 "$output_dir/$name.sh"
done
